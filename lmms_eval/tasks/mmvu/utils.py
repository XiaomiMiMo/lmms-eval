def mmvu_doc_to_visual(doc):
    cache_dir = os.path.join(base_cache_dir, cache_name)
    video_path = os.path.join(cache_dir, doc["video"])
    if os.path.exists(video_path):
        video_path = video_path
    elif os.path.exists(video_path.replace("mp4", "MP4")):
        video_path = video_path.replace("mp4", "MP4")
    elif os.path.exists(video_path.replace("mp4", "mkv")):
        video_path = video_path.replace("mp4", "mkv")
    else:
        sys.exit(f"video path:{video_path} does not exist, please check")
    return [video_path]


def mmvu_doc_to_text(doc, lmms_eval_specific_kwargs=None):
    question = doc["question"]
    if doc['question_type'] == 'open-ended':
        prompt = question
        if "post_prompt_oe" in lmms_eval_specific_kwargs:
            prompt += "\n" + lmms_eval_specific_kwargs["post_prompt_oe"]
    elif doc['question_type'] == 'multiple-choice':
        option = "\n".join(f"{letter}. {option}" for letter, option in doc["choices"].items())
        prompt = question + "\n" + option
        if "post_prompt_mc" in lmms_eval_specific_kwargs:
            prompt += "\n" + lmms_eval_specific_kwargs["post_prompt_mc"] 
    return prompt


def prepare_evaluation_message(example, response):
    user_prompt = ""
    question_type = example["question_type"]
    if question_type == "multiple-choice":
        optionized_list = [f"{key}. {value}" for i, (key, value) in enumerate(example['choices'].items())]
        optionized_str = "\n".join(optionized_list)
        question_context = f"Question: {example['question']}\n\nOptions:\n{optionized_str}"
    elif question_type == "open-ended":
        question_context = f"Question: {example['question']}"
    
    gt_answer = f"Ground Truth Answer: {example['answer']}"
    model_response = f"Model Response to the Question: {response}"
    
    user_prompt = f"{question_context}\n\n{gt_answer}\n\n{model_response}"

    prompt = OPEN_ENDED_INSTRUCTION if question_type == "open-ended" else MULTI_CHOICE_INSTRUCTION
    prompt += "\n\n" + user_prompt
    return prompt


def postprocess_response(eval_res):
    if isinstance(eval_res, str):
        eval_res = json.loads(eval_res)
    extracted_answer = eval_res["extracted_answer"]
    score = int(eval_res["correct"])
    return extracted_answer, score

def mmvu_process_results(doc, results):
    """
    Args:
        doc: a instance of the eval dataset
        results: [pred]
    Returns:
        a dictionary with key: metric name, value: metric value
    """
    global client
    pred = results[0]
    subject = doc["metadata"]["subject"]
    eval_prompt = prepare_evaluation_message(doc, pred)

    messages = [
        {"role": "user", "content": eval_prompt},
    ]
    generation_kwargs = {
        "temperature": 1,
        "top_p": 1,
        "max_tokens": 256,
        "response_format": {"type": "json_object"},
    }
    extracted_answer, score = client.get_chat_response(
        messages, 
        default_response=(None, 0), 
        postprocess_response=postprocess_response,
        generation_kwargs=generation_kwargs
    )
        
    data_dict = {"id": doc["id"], "subject": subject, "pred": pred, "extracted_answer": extracted_answer, "answer": doc["answer"], "score": score}

    return {f"accuracy": data_dict}


def mmvu_aggregate_results(results):
    """
    Args:
        results: a list of values returned by process_results
    Returns:
        A score
    """
    scores = [result['score'] for result in results]
    acc = sum(scores) / len(scores) if len(scores) > 0 else 0
    return acc
